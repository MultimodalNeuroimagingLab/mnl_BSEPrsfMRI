%% ssf_03_preprocess_bsep_crp
%
% Preprocess BSEP/CCEP data and compute canonical response parameters (CRP)
% for the bipolar stimulation pairs selected in Stage 02.
%
% Input:
%   data/vcm_Subjects.mat
%
% vcm_Subjects contains one row per bipolar stimulation pair:
%   .stimEl1    : first stimulation contact
%   .stimEl2    : second stimulation contact
%   .run        : selected BIDS CCEP run
%   .networkYeo : Visual or Control network
%
% Dependencies:
%   - mnl_ieegBasics
%   - matmef
%   - ccep_PreprocessMef
%   - ccep_CAR64blocks_percent1
%   - CRP_method
%   - ssf_loc_colormap
%
% Outputs:
%   data/derivatives/whimstim
%   data/derivatives/preprocPlots
%   data/derivatives/crpMPlots
%
% Author: Maria Guadalupe Yanez Ramos
% Developed with scientific and technical guidance from Dora Hermes
% and the Multimodal Neuroimaging Lab (MNL) team.
% May 2026


clearvars;
clc;
tic;


%% ------------------------------------------------------------------------
% Paths and setup
% -------------------------------------------------------------------------

scriptPath = which('ssf_03_preprocess_bsep_crp');

if isempty(scriptPath)
    error( ...
        'Could not determine the location of ssf_03_preprocess_bsep_crp.m.');
end

codeDir = fileparts(scriptPath);
projectDir = fileparts(codeDir);

localDataPath = fullfile(projectDir, 'data');

% Add project functions
addpath(genpath(fullfile(codeDir, 'functions')));

% Colormap used for preprocessing QC figures
cm = ssf_loc_colormap();

% Load stimulation-pair selection generated by Stage 02
subjectsFile = fullfile( ...
    localDataPath, ...
    'vcm_Subjects.mat');

if ~isfile(subjectsFile)
    error( ...
        ['vcm_Subjects.mat was not found. ' ...
         'Run ssf_02_subject_selection first.']);
end

tmp = load(subjectsFile, 'vcm_Subjects');
vcm_Subjects = tmp.vcm_Subjects;

all_subjects = fieldnames(vcm_Subjects)';

warning off


%% ------------------------------------------------------------------------
% Preprocess subjects
% -------------------------------------------------------------------------

for iSubj = 1:numel(all_subjects)

    %% Subject variables

    bids_sub  = all_subjects{iSubj};
    bids_ses  = 'ieeg01';
    bids_task = 'ccep';

    fprintf( ...
        '\nProcessing subject %s (%d of %d)\n', ...
        bids_sub, ...
        iSubj, ...
        numel(all_subjects));


    %% --------------------------------------------------------------------
    % Create stimulation structure
    % ---------------------------------------------------------------------

    subjectInfo = vcm_Subjects.(bids_sub);

    nStimPairs = height(subjectInfo);

    stim = struct();

    stim.pairs    = cell(nStimPairs, 2);
    stim.events   = cell(nStimPairs, 1);
    stim.channels = cell(nStimPairs, 1);
    stim.mef      = cell(nStimPairs, 1);


    for ss = 1:nStimPairs

        bids_run = subjectInfo.run{ss};
        runStr = char(string(bids_run));

        stimEl1 = string(subjectInfo.stimEl1(ss));
        stimEl2 = string(subjectInfo.stimEl2(ss));

        stim.pairs{ss, 1} = ...
            stimEl1 + "-" + stimEl2;

        stim.pairs{ss, 2} = ...
            string(bids_run);

        ieegDir = fullfile( ...
            localDataPath, ...
            ['sub-' bids_sub], ...
            ['ses-' bids_ses], ...
            'ieeg');

        fileStem = [ ...
            'sub-' bids_sub ...
            '_ses-' bids_ses ...
            '_task-' bids_task ...
            '_run-' runStr];

        stim.events{ss} = fullfile( ...
            ieegDir, ...
            [fileStem '_events.tsv']);

        stim.channels{ss} = fullfile( ...
            ieegDir, ...
            [fileStem '_channels.tsv']);

        stim.mef{ss} = fullfile( ...
            ieegDir, ...
            [fileStem '_ieeg.mefd']);

    end


    %% --------------------------------------------------------------------
    % Save stimulation information
    % ---------------------------------------------------------------------

    whimstimDir = fullfile( ...
        localDataPath, ...
        'derivatives', ...
        'whimstim', ...
        ['sub-' bids_sub]);

    if ~exist(whimstimDir, 'dir')
        mkdir(whimstimDir);
    end

    save( ...
        fullfile( ...
            whimstimDir, ...
            [bids_sub '_stimInfo']), ...
        'stim');


    %% --------------------------------------------------------------------
    % Preprocess each stimulation pair
    % ---------------------------------------------------------------------

    for iii = 1:nStimPairs

        clear prep crp mefObj these_data ...
            data_CRP V crp_parms crp_projs

        stim_pair = stim.pairs{iii, 1};

        fprintf( ...
            '\nStim pair %d of %d: %s\n', ...
            iii, ...
            nStimPairs, ...
            stim_pair);

        disp('-');


        %% ----------------------------------------------------------------
        % Create MEF object
        % -----------------------------------------------------------------

        % ccep_PreprocessMef loads events and channel metadata,
        % but does not load MEF signal data yet.
        mefObj = ccep_PreprocessMef( ...
            stim.mef{iii}, ...
            stim.channels{iii}, ...
            stim.events{iii});


        %% ----------------------------------------------------------------
        % CRP analysis start time
        % -----------------------------------------------------------------

        % Current datasets use gTec recordings.
        % Keep explicit until acquisition-specific timing is generalized.
        t_0 = 0.003;


        %% ----------------------------------------------------------------
        % Identify stimulation contacts and nearby recording channels
        % -----------------------------------------------------------------

        el1 = extractBefore(stim_pair, '-');
        el2 = extractAfter(stim_pair, '-');

        locInfoFile = fullfile( ...
            localDataPath, ...
            'derivatives', ...
            'loc_info', ...
            ['sub-' bids_sub], ...
            'loc_info.mat');

        tmpLoc = load(locInfoFile, 'loc_info');
        loc_info = tmpLoc.loc_info;

        idLocInfo = find( ...
            ismember( ...
                string(loc_info.name), ...
                [string(el1); string(el2)]));

        if numel(idLocInfo) ~= 2
            error( ...
                ['Could not identify both stimulation contacts ' ...
                 'for pair %s in loc_info.'], ...
                stim_pair);
        end

        stimP1 = ...
            table2array(loc_info(idLocInfo(1), 2:4));

        stimP2 = ...
            table2array(loc_info(idLocInfo(2), 2:4));

        neighborStim_channelsName = [];

        for neighNum = 1:height(loc_info)

            recThis = ...
                table2array(loc_info(neighNum, 2:4));

            d1 = norm(stimP2 - recThis);
            d2 = norm(stimP1 - recThis);

            % Exclude recording channels within 8 mm of either
            % stimulation contact.
            if d1 < 8 || d2 < 8

                neighborStim_channelsName = ...
                    [neighborStim_channelsName ...
                     loc_info.name(neighNum)]; %#ok<AGROW>

            end

        end


        %% ----------------------------------------------------------------
        % Select recording channels
        % -----------------------------------------------------------------

        SOZlist = ...
            loc_info.name( ...
                strcmp( ...
                    loc_info.seizure_zone, ...
                    {'SOZ'}));

        use_channels = find( ...
            ismember(mefObj.channels.status, 'good') & ...
            ismember(mefObj.channels.type, {'SEEG'}) & ...
            ~ismember( ...
                mefObj.channels.name, ...
                neighborStim_channelsName) & ...
            ~ismember( ...
                mefObj.channels.name, ...
                SOZlist));

        use_channels_names = ...
            {mefObj.channels.name{use_channels}}';


        %% ----------------------------------------------------------------
        % Load and baseline-correct trials
        % -----------------------------------------------------------------

        mefObj.filterEvents( ...
            'electrical_stimulation_site', ...
            stim_pair);

        mefObj.loadMefTrials( ...
            [-2.5, 2.5]);

        mefObj.subtractBaseline( ...
            [-2.000, -1.000]);


        %% ----------------------------------------------------------------
        % Common average reference and notch filtering
        % -----------------------------------------------------------------

        % Use the 25% lowest-variance channels for the common average.
        perc_channels = 0.25;

        notchOpt.do = 1;
        notchOpt.freq = 60;
        notchOpt.srate = mefObj.srate;

        if notchOpt.srate == 4800

            % gTec: use all channels.
            these_data = ...
                ccep_CAR64blocks_percent1( ...
                    mefObj.data, ...
                    mefObj.tt, ...
                    use_channels, ...
                    perc_channels, ...
                    [t_0 0.500], ...
                    notchOpt, ...
                    0);

        elseif notchOpt.srate == 2048

            % Natus: use 64-channel blocks.
            these_data = ...
                ccep_CAR64blocks_percent1( ...
                    mefObj.data, ...
                    mefObj.tt, ...
                    use_channels, ...
                    perc_channels, ...
                    [t_0 0.500], ...
                    notchOpt, ...
                    1);

        else

            error( ...
                'Unsupported sampling rate: %.1f Hz.', ...
                notchOpt.srate);

        end


        %% ----------------------------------------------------------------
        % Store preprocessing output
        % -----------------------------------------------------------------

        prep = struct();

        prep.data = ...
            these_data;

        prep.tt = ...
            mefObj.tt;

        prep.srate = ...
            mefObj.srate;

        prep.evts = ...
            mefObj.evts;

        prep.use_channels = ...
            use_channels;

        prep.use_channels_names = ...
            use_channels_names;

        prep.channels = ...
            mefObj.channels;


        %% ----------------------------------------------------------------
        % Plot preprocessed responses
        % -----------------------------------------------------------------

        baseRange = ...
            [-0.100, -0.010];

        baselineIdx = ...
            prep.tt >= baseRange(1) & ...
            prep.tt <= baseRange(2);

        these_data = ...
            prep.data - ...
            mean( ...
                prep.data(:, baselineIdx, :), ...
                2);

        fig = figure( ...
            'Visible', ...
            'off');

        imagesc( ...
            prep.tt, ...
            1:numel(prep.use_channels), ...
            median( ...
                these_data(prep.use_channels, :, :), ...
                3), ...
            [-300 300]);

        xlim([-0.1 1]);

        set( ...
            gca, ...
            'YTick', ...
            1:numel(prep.use_channels), ...
            'YTickLabel', ...
            prep.use_channels_names, ...
            'FontSize', ...
            3);

        title( ...
            ['Preprocessed ' char(stim_pair) ...
             ' - median voltage (µV)'], ...
            'FontSize', ...
            7);

        ylabel( ...
            'Channels', ...
            'FontSize', ...
            7, ...
            'FontName', ...
            'Arial');

        xlabel( ...
            'time (s)', ...
            'FontSize', ...
            7, ...
            'FontName', ...
            'Arial');

        colormap(cm);
        colorbar;


        %% Save preprocessing QC figure

        preprocPlotDir = fullfile( ...
            localDataPath, ...
            'derivatives', ...
            'preprocPlots', ...
            ['sub-' bids_sub]);

        if ~exist(preprocPlotDir, 'dir')
            mkdir(preprocPlotDir);
        end

        preprocPlotFile = fullfile( ...
            preprocPlotDir, ...
            [bids_sub '_' ...
             char(stim_pair) ...
             '_preproc.png']);

        print( ...
            fig, ...
            preprocPlotFile, ...
            '-dpng', ...
            '-r600');

        close(fig);


        %% ----------------------------------------------------------------
        % Apply CRP method
        % -----------------------------------------------------------------

        for ii = 1:numel(prep.use_channels_names)

            chNum = ...
                prep.use_channels(ii);

            chName = ...
                prep.use_channels_names{ii};

            data_CRP = ...
                these_data;

            data_CRP = ...
                data_CRP - ...
                mean( ...
                    data_CRP(:, baselineIdx, :), ...
                    2);

            t_lims = ...
                [t_0 1];

            timeIdx = ...
                prep.tt > t_lims(1) & ...
                prep.tt < t_lims(2);

            t_win = ...
                prep.tt(timeIdx);

            V = squeeze( ...
                data_CRP( ...
                    chNum, ...
                    timeIdx, ...
                    :));

            [crp_parms, crp_projs] = ...
                CRP_method( ...
                    V, ...
                    t_win);

            % Coefficient of determination
            ep = ...
                crp_parms.ep;

            V_tR = ...
                crp_parms.V_tR - ...
                mean(crp_parms.V_tR);

            cod = ...
                1 - ...
                ((diag(ep.' * ep)).') ./ ...
                ((diag(V_tR.' * V_tR)).');

            crp(ii).crp_parms = ...
                crp_parms; %#ok<SAGROW>

            crp(ii).crp_projs = ...
                crp_projs;

            crp(ii).use_channels_name = ...
                chName;

            crp(ii).use_channels = ...
                chNum;

            crp(ii).cod = ...
                cod;

        end


        %% ----------------------------------------------------------------
        % Plot CRP traces
        % -----------------------------------------------------------------

        nCh = numel(crp);

        channelsPerPanel = 50;

        nPanels = ...
            ceil(nCh / channelsPerPanel);

        fig = figure( ...
            'Color', ...
            'w', ...
            'Position', ...
            [100 100 1800 450], ...
            'Visible', ...
            'off');

        tiledlayout( ...
            1, ...
            nPanels, ...
            'TileSpacing', ...
            'compact', ...
            'Padding', ...
            'compact');

        y_space = 50;

        xLimits = ...
            [-0.1 0.5];


        for pp = 1:nPanels

            ax = nexttile;

            hold(ax, 'on');

            idxStart = ...
                (pp - 1) * channelsPerPanel + 1;

            idxEnd = ...
                min( ...
                    pp * channelsPerPanel, ...
                    nCh);

            idx = ...
                idxStart:idxEnd;

            nThisPanel = ...
                numel(idx);


            for jj = 1:nThisPanel

                kk = ...
                    idx(jj);

                y0 = ...
                    y_space * jj;

                tt = ...
                    crp(kk).crp_parms.parms_times;

                yy = ...
                    crp(kk).crp_parms.avg_trace_tR;

                plot( ...
                    ax, ...
                    xLimits, ...
                    [y0 y0], ...
                    'Color', ...
                    [0.75 0.75 0.75], ...
                    'LineWidth', ...
                    0.5);

                plot( ...
                    ax, ...
                    tt, ...
                    y0 + yy, ...
                    'LineWidth', ...
                    1.2);

            end


            ylim( ...
                ax, ...
                [0 ...
                 y_space * (nThisPanel + 1)]);

            xlim( ...
                ax, ...
                xLimits);

            yticks( ...
                ax, ...
                y_space * ...
                (1:nThisPanel));

            yticklabels( ...
                ax, ...
                prep.use_channels_names(idx));

            set( ...
                ax, ...
                'YDir', ...
                'reverse', ...
                'FontSize', ...
                7, ...
                'Box', ...
                'off', ...
                'TickDir', ...
                'out');

            xlabel( ...
                ax, ...
                'time (s)');

            if pp == 1

                ylabel( ...
                    ax, ...
                    'recording channel');

                title( ...
                    ax, ...
                    "stim " + string(stim_pair), ...
                    'Interpreter', ...
                    'none');

            end

        end


        %% Save CRP figure

        crpPlotDir = fullfile( ...
            localDataPath, ...
            'derivatives', ...
            'crpMPlots', ...
            ['sub-' bids_sub]);

        if ~exist(crpPlotDir, 'dir')
            mkdir(crpPlotDir);
        end

        crpPlotFile = fullfile( ...
            crpPlotDir, ...
            bids_sub + "_" + ...
            string(stim_pair) + ...
            "_crp.png");

        print( ...
            fig, ...
            char(crpPlotFile), ...
            '-dpng', ...
            '-r300');

        close(fig);


        %% ----------------------------------------------------------------
        % Save preprocessing and CRP results
        % -----------------------------------------------------------------

        outputFile = fullfile( ...
            whimstimDir, ...
            [bids_sub '_' ...
             char(stim_pair) ...
             '_preproc_CRP']);

        save( ...
            outputFile, ...
            'prep', ...
            'crp', ...
            'stim_pair', ...
            '-v7.3');

        fprintf( ...
            'Done with stim pair %d of %d: %s\n', ...
            iii, ...
            nStimPairs, ...
            stim_pair);

        clear mefObj prep crp these_data ...
            data_CRP V crp_parms crp_projs fig ax

    end

end


fprintf('\n');
toc;